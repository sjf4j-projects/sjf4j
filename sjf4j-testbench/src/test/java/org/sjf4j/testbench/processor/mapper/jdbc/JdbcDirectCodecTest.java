package org.sjf4j.testbench.processor.mapper.jdbc;

import org.junit.jupiter.api.Test;
import org.sjf4j.CompiledInstances;
import org.sjf4j.annotation.mapping.jdbc.CompiledJdbcMapper;
import org.sjf4j.annotation.node.NodeProperty;
import org.sjf4j.annotation.node.NodeRegistry;
import org.sjf4j.annotation.node.NodeValue;
import org.sjf4j.mapping.JdbcRowMapper;
import org.sjf4j.value.ValueCodec;
import org.sjf4j.value.ValueRegistry;

import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;
import static org.sjf4j.testbench.processor.mapper.jdbc.JdbcTestSupport.currentRowResult;
import static org.sjf4j.testbench.processor.mapper.jdbc.JdbcTestSupport.result;

/** End-to-end execution of direct ValueCodec calls generated by compiled JDBC. */
class JdbcDirectCodecTest {
    static final String[] COLUMNS = {"tag", "named", "count", "enabled", "document", "items"};

    public static final class Tag {
        public final String text;
        public Tag(String text) { this.text = text; }
    }

    public static final class Count {
        public final long value;
        public Count(long value) { this.value = value; }
    }

    public static final class Switch {
        public final boolean enabled;
        public Switch(boolean enabled) { this.enabled = enabled; }
    }

    public static final class Document {
        public final Map<String, Object> values;
        public Document(Map<String, Object> values) { this.values = values; }
    }

    public static final class Items {
        public final List<?> values;
        public Items(List<?> values) { this.values = values; }
    }

    @NodeRegistry
    public interface Codecs {
        @NodeValue(format = "plain", defaultCodec = true)
        ValueCodec<Tag, String> TAG = new ValueCodec.SimpleValueCodec<>(
                Tag.class, String.class, v -> v.text, raw -> new Tag("plain:" + raw));

        @NodeValue(format = "named")
        ValueCodec<Tag, String> NAMED = new ValueCodec.SimpleValueCodec<>(
                Tag.class, String.class, v -> v.text, raw -> new Tag("named:" + raw));

        ValueCodec<Count, Long> COUNT = new ValueCodec.SimpleValueCodec<>(
                Count.class, Long.class, v -> v.value, Count::new);

        ValueCodec<Switch, Boolean> FLAG = new ValueCodec.SimpleValueCodec<>(
                Switch.class, Boolean.class, v -> v.enabled, Switch::new);

        ValueCodec<Document, Map> DOCUMENT = new ValueCodec.SimpleValueCodec<>(
                Document.class, Map.class, v -> v.values, Document::new);

        ValueCodec<Items, List> ITEMS = new ValueCodec.SimpleValueCodec<>(
                Items.class, List.class, v -> v.values, Items::new);
    }

    public static final class Row {
        public Tag tag;
        @NodeProperty(valueFormat = "named")
        public Tag named;
        public Count count;
        public Switch enabled;
        public Document document;
        public Items items;
    }

    public record RecordRow(Tag tag, Count count) {}

    @CompiledJdbcMapper(registries = Codecs.class)
    interface Mapper {
        Row map(ResultSet rs);
        List<Row> all(ResultSet rs);
        JdbcRowMapper<Row> prepare(ResultSetMetaData metadata);
        RecordRow record(ResultSet rs);
    }

    private final Mapper mapper = CompiledInstances.create(Mapper.class);

    private static Object[] data() {
        return new Object[]{"A", "B", 12L, true,
                Map.of("name", "Ada"), List.of("x", 2)};
    }

    private static void assertRow(Row row) {
        assertEquals("plain:A", row.tag.text);
        assertEquals("named:B", row.named.text);
        assertEquals(12L, row.count.value);
        assertTrue(row.enabled.enabled);
        assertEquals("Ada", row.document.values.get("name"));
        assertEquals(List.of("x", 2), row.items.values);
    }

    @Test
    void directDecodingDoesNotRequireRuntimeValueRegistry() {
        assertNull(ValueRegistry.resolve(Tag.class));
        assertNull(ValueRegistry.resolve(Count.class));
        assertRow(mapper.map(result(COLUMNS, data())));
        assertNull(ValueRegistry.resolve(Tag.class));
    }

    @Test
    void nullColumnsArePassedToCodecsWithoutSyntheticValues() {
        Row row = mapper.map(result(COLUMNS,
                new Object[]{null, null, null, null, null, null}));
        assertNull(row.tag);
        assertNull(row.named);
        assertNull(row.count);
        assertNull(row.enabled);
        assertNull(row.document);
        assertNull(row.items);
    }

    @Test
    void listAndPreparedMapperUseSameDirectCodecPath() {
        List<Row> rows = mapper.all(result(COLUMNS, data(), data()));
        assertEquals(2, rows.size());
        rows.forEach(JdbcDirectCodecTest::assertRow);

        int[] nextCalls = {0};
        JdbcRowMapper<Row> prepared = mapper.prepare(JdbcTestSupport.metadata(COLUMNS));
        Row current = prepared.map(currentRowResult(COLUMNS, nextCalls, data()));
        assertRow(current);
        assertEquals(0, nextCalls[0], "prepared mapper must not advance ResultSet");
    }

    @Test
    void constructorBasedMappingUsesDirectCodecFields() {
        RecordRow record = mapper.record(result(
                new String[]{"tag", "count"}, new Object[]{"R", 7L}));
        assertEquals("plain:R", record.tag().text);
        assertEquals(7L, record.count().value);
    }
}
